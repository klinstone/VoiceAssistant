"""Описание настроек для окна «Настройки»: группы, названия, подсказки, типы, диапазоны, «нужен ли перезапуск».
Окно строится из этого списка автоматически. Новая настройка = значение по умолчанию в config.py (или settings.py)
+ одна строка здесь. Без Qt, поэтому файл можно проверять и править отдельно от интерфейса."""
from dataclasses import dataclass


@dataclass
class Field:
    key: str                    # имя в config.py / settings.py
    group: str
    title: str
    kind: str                   # bool | int | float | str | text | secret | choice | combo | mic | strlist | tools | dict
    help: str = ""
    restart: bool = False       # изменение вступает в силу только после перезапуска
    env: bool = False           # хранится в .env, а не в settings.json
    min: float = 0
    max: float = 100
    step: float = 1
    decimals: int = 2
    suffix: str = ""
    options: tuple = ()         # для choice / combo: ((значение, подпись), ...)
    models: str = ""            # combo с кнопкой «загрузить список с OpenRouter»: "llm" | "vision"
    test: str = ""              # кнопка проверки рядом с полем: "voice"
    browse: bool = False        # dict: кнопка выбора файла
    key_title: str = "Название"
    value_title: str = "Значение"


